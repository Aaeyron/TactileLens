"""Regenerate meaning_holds_shared.json from the Python rules.

Run from ai_service/:  python -m services.braille.fixtures.generate_meaning_holds_fixture
The Flutter test frontend/test/services/braille/offline_braille_holds_test.dart
checks the app's on-device holds against the same file.
"""

import json
from pathlib import Path

from services.braille import meaning_holds as holds

# Formula LaTeX as OCR returns it. Same cases as the Flutter unit tests.
CASES = [
    r"a\neq 0", r"a\ne b", r"3x-5\leq 10", r"x\le 4", r"x \geq -2", r"x\ge 1",
    r"x\geqslant 0", r"\pi\approx 3.14", "x ≤ 3",
    r"x^{n+1}", r"x^{n+1}y", r"2^{x+1}=8", r"e^{2x}+1", r"x^{2n}", r"x^{-1}y",
    r"2^{3}4", r"\log_{2}8=3", r"2^{10}x", r"a_{n+1}=2a_{n}", r"x_{12}y",
    r"\{1,2,3\}", r"A=\lbrace x \rbrace",
    r"2x+3=7", r"x^{2}-5x+6=0", r"\frac{x+1}{2}=3", r"y=mx+b",
    r"x^{2}+y^{2}=r^{2}", r"\left(x+2\right)\left(x-3\right)", r"\frac{3x}{10}=6",
    r"2\left(x-4\right)=10", r"x \times 3 = 12", r"12 \div 4 = 3",
    r"-\frac{1}{2}x+4", r"x = 3.5", r"f(x)=2x^{3}-1", r"\pi r^{2}", r"x_{1}+x_{2}",
    r"10^{-3}", r"2^{10}", r"\left(x^{12}\right)", r"3x^{2}y", r"x^{2 \cdot x}",
    r"x<5", r"y>-1",
    r"x^{n+1}\leq\{1\}",
    # Table row text (no LaTeX), as the server builds it.
    "Row 1: x ≤ 3, y = 2", "Row 1: Input, A, 1",
]


def main() -> None:
    cases = []

    for content in CASES:
        review = holds.review_meaning(content)
        cases.append(
            {
                "input": content,
                "needs_review": review.needs_review,
                "categories": list(review.categories),
                "reason": review.reason,
            }
        )

    fixture = {
        "about": (
            "Holds for math whose Braille would read as another formula. "
            "Generated by generate_meaning_holds_fixture.py from "
            "services/braille/meaning_holds.py; the app's "
            "offline_braille_holds.dart must give the same result."
        ),
        "reasons": {
            holds.RELATION_SIGN: holds.RELATION_SIGN_REASON,
            holds.SCRIPT_GROUPING: holds.SCRIPT_GROUPING_REASON,
            holds.SET_BRACES: holds.SET_BRACES_REASON,
        },
        "cases": cases,
    }

    path = Path(__file__).resolve().parent / "meaning_holds_shared.json"
    path.write_text(
        json.dumps(fixture, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"{len(cases)} cases written to {path.name}")


if __name__ == "__main__":
    main()
