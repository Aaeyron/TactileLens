"""A FAKE delivery for dry runs of intake.py and split_dataset.py.

  python make_fake_intake.py --out C:\\temp\\fake_incoming --leak-from <root>\\eval\\synthetic

Everything is generated here (drawn text with an open font and the word
FAKE on every image); nothing is real data and nothing must be trained on.
It writes one zip (FAKE_dryrun_dataset.zip) and one folder
(FAKE_dryrun_extra/) in our naming scheme, with problems planted on
purpose so the dry run shows they are caught:

  leak          an image copied from an existing eval set (--leak-from)
  broken label  \\sqrt{x+9=5 (brace not closed)
  ss/cap pair   fractions_ss_S_001 / fractions_cap_S_001, same target
  duplicates    an exact byte copy and a re-saved JPEG near-duplicate
  personal      "Name: ... Section: ..." text and a photo with GPS in EXIF
  charset       a text line with a letter superscript the recognizer lacks
  names         IMG_2041.jpg (not in the scheme)
  missing       an image without a label, a label without an image
"""

from __future__ import annotations

import argparse
import csv
import io
import random
import shutil
import zipfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

FONT = Path(r"C:\Projects\Capstone\tactilelens-training\fonts\dejavu\DejaVuSans.ttf")

README = """THIS IS A FAKE DATASET FOR A DRY RUN. DO NOT TRAIN ON IT.
Generated by TactileLens tools/dataset/make_fake_intake.py.
Every image says FAKE; several problems are planted on purpose.
"""

TOPICS = {
    "fractions": [(r"\frac{1}{2}+\frac{1}{3}", "1/2 + 1/3"), (r"\frac{x}{4}=3", "x/4 = 3"),
                  (r"\frac{a+b}{c}", "(a+b)/c"), (r"\frac{3}{5}-\frac{1}{5}", "3/5 - 1/5"),
                  (r"\frac{2x}{7}", "2x/7"), (r"\frac{9}{10}", "9/10"), (r"\frac{y-1}{2}=4", "(y-1)/2 = 4")],
    "exponents": [(r"x^{2}+3x", "x² + 3x"), (r"a^{3}b^{2}", "a³b²"), (r"10^{-3}", "10⁻³"),
                  (r"2^{5}=32", "2⁵ = 32"), (r"y^{-2}", "y⁻²"), (r"(xy)^{4}", "(xy)⁴"), (r"5^{0}=1", "5⁰ = 1")],
    "radicals": [(r"\sqrt{16}=4", "√16 = 4"), (r"\sqrt{x+9}=5", "√(x+9) = 5"), (r"\sqrt[3]{27}=3", "∛27 = 3"),
                 (r"2\sqrt{3}", "2√3"), (r"\sqrt{50}", "√50"), (r"\sqrt{a^{2}}", "√(a²)"), (r"\sqrt{81}=9", "√81 = 9")],
    "linear_equations": [(r"2x+5=11", "2x + 5 = 11"), (r"3y-4=8", "3y - 4 = 8"), (r"x-7=2", "x - 7 = 2"),
                         (r"4a=20", "4a = 20"), (r"5m+1=16", "5m + 1 = 16"), (r"6-x=1", "6 - x = 1"),
                         (r"7n=49", "7n = 49")],
}
TEXTS = {
    "fractions": "Add the fractions and simplify.",
    "exponents": "Write the answer with a positive exponent.",
    "radicals": "Simplify each square root.",
    "linear_equations": "Solve for x and check your answer.",
}


def font(size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(str(FONT), size) if FONT.exists() else ImageFont.load_default(size)


def draw(text: str, photo: bool, rng: random.Random) -> Image.Image:
    f = font(40)
    width = int(f.getlength(text)) + 140
    image = Image.new("RGB", (max(width, 260), 110), (255, 255, 255))
    d = ImageDraw.Draw(image)
    d.text((30, 30), text, font=f, fill=(0, 0, 0))
    d.text((image.width - 70, 4), "FAKE", font=font(16), fill=(200, 0, 0))
    if photo:  # a rough "phone capture" look
        image = image.rotate(rng.uniform(-3, 3), expand=True, fillcolor=(235, 230, 220))
        image = image.filter(ImageFilter.GaussianBlur(0.8))
        tint = Image.new("RGB", image.size, (250, 240, 215))
        image = Image.blend(image, tint, 0.25)
    return image


def table_image(rows: list[list[str]]) -> Image.Image:
    f = font(30)
    w, h = 110, 56
    image = Image.new("RGB", (w * len(rows[0]) + 40, h * len(rows) + 60), (255, 255, 255))
    d = ImageDraw.Draw(image)
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            x, y = 20 + c * w, 40 + r * h
            d.rectangle([x, y, x + w, y + h], outline=(0, 0, 0), width=2)
            d.text((x + 16, y + 10), text, font=f, fill=(0, 0, 0))
    d.text((image.width - 70, 4), "FAKE", font=font(16), fill=(200, 0, 0))
    return image


def png(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True, help="the fake 'incoming' folder (created)")
    parser.add_argument("--leak-from", help="an eval set folder with labels.txt (an image is copied in as a leak)")
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    files: dict[str, bytes] = {}
    rows: list[dict] = []

    def add(name: str, data: bytes | None, task: str | None, target: str | None, split: str = "") -> None:
        if data is not None:
            topic = name.split("_ss_")[0].split("_cap_")[0] if ("_ss_" in name or "_cap_" in name) else "other"
            files[f"{topic}/{name}"] = data
        if task is not None:
            rows.append({"filename": name, "task": task, "target": target, "split": split})

    for topic, formulas in TOPICS.items():
        for n, (latex, drawn) in enumerate(formulas[:4], 1):
            add(f"{topic}_ss_S_{n:03d}.png", png(draw(drawn, False, rng)), "formula", latex)
        for n, (latex, drawn) in enumerate(formulas[4:], 5):
            add(f"{topic}_cap_S_{n:03d}.png", png(draw(drawn, True, rng)), "formula", latex)
        add(f"{topic}_ss_T_001.png", png(draw(TEXTS[topic], False, rng)), "text", TEXTS[topic])
        add(f"{topic}_cap_T_002.png", png(draw("Show your work.", True, rng)), "text", f"Show your work ({topic}).")
        latex, drawn = formulas[0]
        add(f"{topic}_ss_M_001.png", png(draw(f"{drawn}   and   {formulas[1][1]}", False, rng)), "formula",
            f"{latex} \\quad {formulas[1][0]}")
    add("tables_ss_M_001.png", png(table_image([["x", "y"], ["1", "2"], ["3", "4"]])), "table",
        "<fcel>x<fcel>y<nl><fcel>1<fcel>2<nl><fcel>3<fcel>4<nl>")
    add("tables_cap_M_002.png", png(table_image([["n", "n²"], ["2", "4"]]).rotate(2, expand=True, fillcolor=(230, 225, 215))),
        "table", "<fcel>n<fcel>n²<nl><fcel>2<fcel>4<nl>", split="eval")

    # Planted problems.
    add("fractions_cap_S_001.png", png(draw("1/2 + 1/3", True, rng)), "formula", r"\frac{1}{2}+\frac{1}{3}")  # ss/cap pair
    add("radicals_ss_S_091.png", png(draw("√(x+9) = 5", False, rng)), "formula", r"\sqrt{x+9=5")  # broken label
    add("exponents_ss_S_092.png", files["exponents/exponents_ss_S_002.png"], "formula", r"a^{3}b^{2}")  # exact copy
    near = Image.open(io.BytesIO(files["exponents/exponents_ss_S_003.png"])).convert("RGB")
    near = near.resize((near.width - 6, near.height - 2))
    buffer = io.BytesIO()
    near.save(buffer, format="JPEG", quality=60)
    add("exponents_ss_S_093.jpg", buffer.getvalue(), "formula", r"10^{-3} ")  # near-duplicate
    personal = draw("Name: Juan Santos   Section: 7-A", True, rng)
    exif = Image.Exif()
    gps = exif.get_ifd(0x8825)
    gps[1], gps[2], gps[3], gps[4] = "N", (14.0, 35.0, 0.0), "E", (120.0, 59.0, 0.0)
    buffer = io.BytesIO()
    personal.save(buffer, format="JPEG", quality=90, exif=exif)
    add("linear_equations_cap_T_094.jpg", buffer.getvalue(), "text", "Name: Juan Santos   Section: 7-A")
    add("exponents_ss_T_095.png", png(draw("xˣ grows fast", False, rng)), "text", "xˣ grows fast")  # charset
    files["other/IMG_2041.jpg"] = png(draw("2 + 2", True, rng))
    rows.append({"filename": "IMG_2041.jpg", "task": "formula", "target": "2+2", "split": ""})
    add("radicals_cap_S_096.png", png(draw("√49 = 7", True, rng)), None, None)  # no label
    rows.append({"filename": "fractions_ss_S_097.png", "task": "formula", "target": r"\frac{5}{8}", "split": ""})

    if args.leak_from:  # a copy of an existing eval image, renamed into the scheme
        source = Path(args.leak_from)
        first = (source / "labels.txt").read_text(encoding="utf-8").splitlines()[0]
        image, label = first.split("\t", 1)
        add("exponents_ss_T_090.png", (source / image).read_bytes(), "text", label)

    zip_items = {k: v for k, v in files.items() if not k.startswith("linear_equations/")}
    with zipfile.ZipFile(out / "FAKE_dryrun_dataset.zip", "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("README_FAKE.txt", README)
        for name, data in sorted(zip_items.items()):
            zf.writestr(name, data)
        text = io.StringIO()
        writer = csv.DictWriter(text, fieldnames=["filename", "task", "target", "split"])
        writer.writeheader()
        writer.writerows(r for r in rows if not r["filename"].startswith("linear_equations_"))
        zf.writestr("labels.csv", text.getvalue())

    extra = out / "FAKE_dryrun_extra"
    if extra.exists():
        shutil.rmtree(extra)
    extra.mkdir()
    (extra / "README_FAKE.txt").write_text(README, encoding="utf-8")
    for name, data in files.items():
        if name.startswith("linear_equations/"):
            (extra / name).parent.mkdir(parents=True, exist_ok=True)
            (extra / name).write_bytes(data)
    with open(extra / "labels_linear.csv", "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["filename", "task", "target", "split"])
        writer.writeheader()
        writer.writerows(r for r in rows if r["filename"].startswith("linear_equations_"))

    print(f"FAKE delivery in {out}: {len(files)} images, {len(rows)} label rows (zip + folder)")


if __name__ == "__main__":
    main()
